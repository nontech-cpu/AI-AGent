"""
PeculiarAI — Promote Suspect Turns into Regression Tests (Part 6)
Pulls suspect / failed turns from turn_traces, anonymizes them, and generates permanent regression test fixtures.
"""
import os
import sys
import re
import json

root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if root_dir not in sys.path:
    sys.path.insert(0, root_dir)

from sqlalchemy import text
import db

def anonymize_text(t: str) -> str:
    """Replaces personal names, emails, and phones with generic placeholders."""
    if not t:
        return ""
    # Anonymize emails
    t = re.sub(r"[a-zA-Z0-9_\-\.]+@[a-zA-Z0-9_\-\.]+\.[a-zA-Z]{2,}", "user@example.com", t)
    # Anonymize phone numbers
    t = re.sub(r"\+?[0-9]{10,14}", "+919876543210", t)
    # Anonymize specific names
    for name in ["Nirav", "Ananya", "Rahul", "Priya"]:
        t = re.sub(rf"\b{name}\b", "TestUser", t, flags=re.IGNORECASE)
    return t

def promote_suspects():
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target_test_file = os.path.join(root_dir, "tests", "test_promoted_suspects.py")

    suspect_rows = []
    try:
        with db.engine.begin() as conn:
            suspect_rows = conn.execute(text("""
                SELECT trace_id, message, detected_connector, tools_called,
                       guard_results, suspect_reason
                FROM turn_traces
                WHERE is_suspect = TRUE
                ORDER BY id DESC LIMIT 50
            """)).fetchall()
    except Exception as exc:
        print("Error reading suspect turns:", repr(exc))
        return

    if not suspect_rows:
        print("No unpromoted suspect turns found.")
        return

    print(f"Found {len(suspect_rows)} suspect turns to promote.")

    cases = []
    for r in suspect_rows:
        tid, msg, conn, tools, guards, reason = r
        clean_msg = anonymize_text(msg or "")
        cases.append({
            "trace_id": tid,
            "message": clean_msg,
            "connector": conn or "unknown",
            "reason": reason or "guard_violation"
        })

    code = [
        '"""',
        'Auto-generated regression tests from promoted suspect production turns.',
        'Generated by scripts/promote_suspects.py.',
        '"""',
        'import pytest',
        'from connectors.guardrails import check_fake_success_guard, sanitize_untrusted_content',
        '',
        'SUSPECT_CASES = ' + json.dumps(cases, indent=2),
        '',
        '@pytest.mark.parametrize("case", SUSPECT_CASES, ids=lambda c: c["trace_id"])',
        'def test_promoted_suspect_regression_check(case):',
        '    """Verifies that past failure prompts are sanitized and guarded."""',
        '    msg = case["message"]',
        '    cleaned = sanitize_untrusted_content(msg)',
        '    assert cleaned is not None',
        '    # Ensure no raw unconfirmed completion claim passes',
        '    is_ok, err = check_fake_success_guard(msg, [])',
        '    # If message had completion claims, fake_success_guard must catch it without tools',
        '    if any(w in msg.lower() for w in ["ho gaya", "bhej diya", "created"]):',
        '        assert is_ok is False',
        ''
    ]

    with open(target_test_file, "w", encoding="utf-8") as f:
        f.write("\n".join(code))

    print(f"Successfully promoted {len(cases)} suspect cases into {target_test_file}.")

if __name__ == "__main__":
    promote_suspects()
